# Python If Statement


'''
Equals: a == b
Not Equals: a != b
Less than: a < b
Less than or equal to: a <= b
Greater than: a > b
Greater than or equal to: a >= b
'''




# If Statement

a = 33
b = 200
if b > a:
  print("b is greater than a")



# Checking if a number is positive:

number = 15
if number > 0:
  print("The number is positive")





