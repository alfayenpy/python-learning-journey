# Data types in Python include:
# 1. int: Represents integer numbers (e.g., 5, -3, 0)
# 2. float: Represents floating-point numbers (e.g., 3.14, -0.5)
# 3. str: Represents strings, which are sequences of characters (e.g., "Hello", 'Python')
# 4. bool: Represents boolean values, which can be either True or False
# 5. list: Represents ordered collections of items (e.g., [1, 2, 3], ["apple", "banana"])
# 6. tuple: Represents ordered, immutable collections of items (e.g., (1, 2, 3), ("apple", "banana"))
# 7. dict: Represents key-value pairs (e.g., {"name": "John", "age": 30})
# 8. set: Represents unordered collections of unique items (e.g., {1, 2, 3}, {"apple", "banana"})
# 9. NoneType: Represents the absence of a value (e.g., None)











