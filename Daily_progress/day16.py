# Remove List Items


'''

remove()
pop()
del

'''



# Remove()  =  removes by value


players = ["player1", "player2", "player3"]
players.remove("player2")

print(players)


# pop()   =   removes by Index


vegetables = ["aalu", "loki", "khira", "mirchi", "kela"]

vegetables.pop(2)

print(vegetables)



# Special POP   =   if vegetables.pop()     then python removes the last item from the list







# del   =       Deletes using Index

del vegetables[1]

print(vegetables)

