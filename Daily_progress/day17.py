# Python Loop Lists


# For loop

'''
Take one country
from countries
again and again
until the list finishes.
'''




countries = ["albania", "osaka", "kyoto", "Japan"]

for country in countries:
    print(countries)




items = ["toy", "book", "pen", "pencil"]

