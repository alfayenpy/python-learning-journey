# Python Set Methods




# pop() 

numbers = {10, 20, 30}

numbers.pop()

print(numbers)



# clear()


numbers = {10, 20, 30}

numbers.clear()

print(numbers)




# copy()


set1 = {"India", "Japan"}

set2 = set1.copy()

print(set2)





# len
myset = {"dsa"}

print(len(myset))





# in

print("India" in myset)


